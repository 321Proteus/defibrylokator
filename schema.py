SCHEMA_SQL = """
CREATE TABLE IF NOT EXISTS operatorzy (
    operator_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nazwa text NOT NULL,
    telefon text,
    wikidata text
);

CREATE UNIQUE INDEX IF NOT EXISTS operatorzy_nazwa_uidx ON operatorzy (lower(btrim(nazwa)));

CREATE TABLE IF NOT EXISTS defibrylatory (
    defibrylator_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    zrodlo text NOT NULL,
    zrodlo_id text,

    lat double precision NOT NULL CHECK (lat BETWEEN 49.0 AND 55.0),
    lon double precision NOT NULL CHECK (lon BETWEEN 14.1 AND 24.2),
    
    nazwa text,
    gdzie_dokladnie text,
    pietro text,
    wewnatrz boolean,

    -- adres: z geokodowania odwrotnego (lat/lon -> adres) lub wpisany ręcznie, gdy ono zawiedzie;
    -- format (np. kod pocztowy) walidowany po stronie serwera
    adres text,

    dostepnosc text NOT NULL DEFAULT 'nieznana'
        CHECK (dostepnosc IN ('publiczna', 'klienci', 'zezwolenie', 'dozwolona', 'prywatna', 'nieznana')),
    godziny_otwarcia text,

    operator_id bigint REFERENCES operatorzy(operator_id),
    telefon text,

    status text CHECK (status IN ('sprawny', 'w_serwisie', 'nieaktywny')),
    ostatnia_weryfikacja text CHECK (ostatnia_weryfikacja ~ '^[0-9]{4}(-[0-9]{2}(-[0-9]{2})?)?$'),

    uwagi text,
    zdjecie_url text,
    inne jsonb,

    -- różne źródła mogą opisywać różne urządzenia w tym samym punkcie (piętra, szafki),
    -- więc (lat, lon) nie jest unikalne; unikalny jest rekord ze źródła
    UNIQUE (zrodlo, zrodlo_id)
);

CREATE INDEX IF NOT EXISTS defibrylatory_lat_lon_idx ON defibrylatory (lat, lon);
CREATE INDEX IF NOT EXISTS defibrylatory_operator_idx ON defibrylatory (operator_id);

COMMENT ON TABLE operatorzy                              IS 'Operatorzy AED i ich dane kontaktowe.';
COMMENT ON TABLE defibrylatory                           IS 'Lokalizacje defibrylatorów AED zebrane z wielu źródeł.';

COMMENT ON COLUMN operatorzy.operator_id                 IS 'Techniczny klucz operatora';
COMMENT ON COLUMN operatorzy.nazwa                       IS 'Nazwa operatora lub właściciela AED (unikalna bez względu na wielkość liter)';
COMMENT ON COLUMN operatorzy.telefon                     IS 'Telefon kontaktowy operatora';
COMMENT ON COLUMN operatorzy.wikidata                    IS 'Identyfikator Wikidata operatora, np. Q3182097';

COMMENT ON COLUMN defibrylatory.defibrylator_id          IS 'Techniczny klucz defibrylatora';
COMMENT ON COLUMN defibrylatory.zrodlo                   IS 'Nazwa źródła danych, np. osm, dane.gov.pl, nazwa dysponenta';
COMMENT ON COLUMN defibrylatory.zrodlo_id                IS 'Identyfikator rekordu w źródle, np. node/123456 dla OSM';
COMMENT ON COLUMN defibrylatory.lat                      IS 'Szerokość geograficzna WGS84';
COMMENT ON COLUMN defibrylatory.lon                      IS 'Długość geograficzna WGS84';
COMMENT ON COLUMN defibrylatory.nazwa                    IS 'Nazwa obiektu w którym znajduje się urządzenie';
COMMENT ON COLUMN defibrylatory.gdzie_dokladnie          IS 'Dokładny opis położenia AED w obiekcie lub na pojeździe';
COMMENT ON COLUMN defibrylatory.pietro                   IS 'Piętro lub poziom na którym znajduje się urządzenie (np. 0, -1, G)';
COMMENT ON COLUMN defibrylatory.wewnatrz                 IS 'Czy AED jest wewnątrz budynku; NULL = nieznane';
COMMENT ON COLUMN defibrylatory.adres                    IS 'Adres w jednym polu, np. ul. Marszałkowska 1, 00-001 Warszawa; z geokodowania odwrotnego lub wpisany ręcznie';
COMMENT ON COLUMN defibrylatory.dostepnosc               IS 'Kto może użyć AED: publiczna (każdy), klienci, zezwolenie (po uzyskaniu zgody), dozwolona (tolerowana), prywatna, nieznana';
COMMENT ON COLUMN defibrylatory.godziny_otwarcia         IS 'Godziny dostępności w składni OSM opening_hours, np. 24/7 lub Mo-Fr 07:30-15:30';
COMMENT ON COLUMN defibrylatory.operator_id              IS 'Operator urządzenia';
COMMENT ON COLUMN defibrylatory.telefon                  IS 'Telefon kontaktowy przy urządzeniu, np. 112';
COMMENT ON COLUMN defibrylatory.status                   IS 'Stan urządzenia: sprawny, w_serwisie, nieaktywny; NULL = nieznany';
COMMENT ON COLUMN defibrylatory.ostatnia_weryfikacja     IS 'Data ostatniej weryfikacji danych: RRRR, RRRR-MM lub RRRR-MM-DD';
COMMENT ON COLUMN defibrylatory.uwagi                    IS 'Dodatkowe uwagi tekstowe';
COMMENT ON COLUMN defibrylatory.zdjecie_url              IS 'Adres zdjęcia urządzenia lub jego otoczenia';
COMMENT ON COLUMN defibrylatory.inne                     IS 'Pozostałe atrybuty ze źródła, które nie mają własnej kolumny';
"""
