SCHEMA_SQL = """
CREATE TABLE IF NOT EXISTS operatorzy (
    operator_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nazwa text NOT NULL UNIQUE,
    telefon text
);
CREATE TABLE IF NOT EXISTS defibrylatory (
    defibrylatory_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lat double precision NOT NULL,
    lon double precision NOT NULL,
    nazwa text,
    opis text,
    gdzie_dokladnie text,
    dostepnosc text NOT NULL,
    wewnatrz boolean,
    godziny_otwarcia text,
    operator_id bigint REFERENCES operatorzy(operator_id),
    pietro text,
    ostatnie_sprawdzenie text,
    zmodyfikowano_osm timestamptz,
    UNIQUE (lat, lon)
);
CREATE INDEX IF NOT EXISTS defibrylatory_lat_lon_idx ON defibrylatory (lat, lon);
CREATE INDEX IF NOT EXISTS defibrylatory_operator_idx ON defibrylatory (operator_id);

COMMENT ON TABLE operatorzy IS 'Operatorzy AED i ich telefony kontaktowe.';
COMMENT ON TABLE defibrylatory IS 'Lokalizacje defibrylatorów AED z OpenStreetMap.';

COMMENT ON COLUMN operatorzy.operator_id IS 'Techniczny klucz operatora.';
COMMENT ON COLUMN operatorzy.nazwa IS 'Nazwa operatora lub właściciela AED.';
COMMENT ON COLUMN operatorzy.telefon IS 'Telefon kontaktowy operatora.';
COMMENT ON COLUMN defibrylatory.defibrylatory_id IS 'Techniczny klucz defibrylatora.';
COMMENT ON COLUMN defibrylatory.lat IS 'Szerokość geograficzna WGS84.';
COMMENT ON COLUMN defibrylatory.lon IS 'Długość geograficzna WGS84.';
COMMENT ON COLUMN defibrylatory.nazwa IS 'Nazwa obiektu z OSM.';
COMMENT ON COLUMN defibrylatory.opis IS 'Opis AED z OSM.';
COMMENT ON COLUMN defibrylatory.gdzie_dokladnie IS 'Dokładny opis miejsca AED.';
COMMENT ON COLUMN defibrylatory.dostepnosc IS 'Dostępność AED po polsku.';
COMMENT ON COLUMN defibrylatory.wewnatrz IS 'Czy AED jest wewnątrz budynku.';
COMMENT ON COLUMN defibrylatory.godziny_otwarcia IS 'Godziny dostępności według OSM.';
COMMENT ON COLUMN defibrylatory.operator_id IS 'Operator AED.';
COMMENT ON COLUMN defibrylatory.pietro IS 'Piętro lub poziom AED.';
COMMENT ON COLUMN defibrylatory.ostatnie_sprawdzenie IS 'Data ostatniego sprawdzenia z OSM.';
COMMENT ON COLUMN defibrylatory.zmodyfikowano_osm IS 'Czas ostatniej zmiany obiektu w OSM.';
"""